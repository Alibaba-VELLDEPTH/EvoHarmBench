# 风险类型关键词映射（用于回退匹配）
RISK_TYPE_STRATEGY_MAP = {
    "色情": PORNOGRAPHY_STRATEGY,
    "辱骂": ABUSE_STRATEGY,
    "灌水": SPAM_STRATEGY,
    "赌博欺诈": GAMBLING_FRAUD_STRATEGY,
}


def detect_risk_type_from_category(category: str) -> str | None:
    """根据类别名称中的关键词识别风险类型"""
    keywords_map = {
        "色情": ["色情", "壮阳", "裸聊", "嫖娼", "卖淫", "性", "欲", "高潮", "口爱", "恋足", "资源", "视频", "写真"],
        "辱骂": ["辱骂", "诅咒", "侮辱", "驱逐", "人格贬低", "死亡诅咒", "粗口", "性别侮辱", "亲属诅咒", "智力侮辱"],
        "灌水": ["灌水", "顶帖", "围观", "抢楼", "表情", "标点", "无意义", "回复", "笑声"],
        "赌博欺诈": ["赌博", "欺诈", "棋牌", "博彩", "诈骗", "金融", "杀猪盘", "刷单", "贷款", "套现"],
        "引流": ["引流", "微信", "手机号", "QQ", "搜索", "电商", "买手", "群聊", "平台账号"],
    }
    for risk_type, keywords in keywords_map.items():
        for kw in keywords:
            if kw in category:
                return risk_type
    return None


def get_strategy(category: str) -> str:
    """
    获取指定类别的初始策略

    匹配逻辑：
    1. 精确匹配：如"微信号直发"返回对应策略
    2. 风险类型回退：如"壮阳保健品评价-1"返回色情通用策略

    Args:
        category: 聚类类别名称

    Returns:
        对应的策略prompt
    """
    # 1. 精确匹配
    if category in INITIAL_STRATEGIES:
        return INITIAL_STRATEGIES[category]

    # 2. 按风险类型回退匹配
    risk_type = detect_risk_type_from_category(category)
    if risk_type and risk_type in RISK_TYPE_STRATEGY_MAP:
        return RISK_TYPE_STRATEGY_MAP[risk_type]

    # 3. 默认返回其他引流方式策略
    return OTHER_DRAINAGE_STRATEGY


def list_strategies() -> dict:
    """
    列出所有可用策略及其长度

    Returns:
        {类别名称: 策略长度}
    """
    return {
        name: len(strategy)
        for name, strategy in INITIAL_STRATEGIES.items()
    }


